const NB: usize = 16;
const PER: usize = 128;
const NSIG: usize = NB * PER;

struct Tally {
    pass: usize,
    total: usize,
    unexpected: Vec<String>,
}

impl Tally {
    fn expect(&mut self, name: &str, res: &Result<cert::VerifyReport, Reject>, accept: bool) {
        self.total += 1;
        let ok = res.is_ok() == accept;
        self.pass += ok as usize;
        if !ok {
            self.unexpected.push(name.to_string());
        }
        let v = match res {
            Ok(_) => "ACCEPT".to_string(),
            Err(e) => format!("REJECT {e:?}"),
        };
        println!("[{}] {name}: {v}", if ok { "PASS" } else { "FAIL" });
    }
    fn check(&mut self, name: &str, ok: bool) {
        self.total += 1;
        self.pass += ok as usize;
        if !ok {
            self.unexpected.push(name.to_string());
        }
        println!("[{}] {name}", if ok { "PASS" } else { "FAIL" });
    }
}

fn honest_inputs(ntt: &Ntt, ch: &Chain) -> Vec<SigInput> {
    let records = chain::replay(&ch.net, &ch.blocks[..NB], &ch.state).unwrap();
    let sigs: Vec<Vec<u8>> = ch.blocks[..NB].iter().flat_map(|b| b.sigs.clone()).collect();
    records.par_iter().zip(sigs.par_iter()).map(|(r, s)| witness::input_from_raw(ntt, r, s)).collect()
}

type WTweak<'a> = Option<&'a (dyn Fn(&mut Witness) + Sync)>;
type NuTweak<'a> = Option<&'a dyn Fn(&mut Vec<u8>)>;

/// Prove the range under 0x00070001 with the given (z, u) per record. `wt` mutates the witness
/// after generation; `nut` receives the unclamped true counts and returns the published ones
/// (default: min(count, 75)); `o` holds prover-side test options.
fn prove(ch: &Chain, inputs: &[SigInput], wt: WTweak, nut: NuTweak, o: &cert::Opts) -> Vec<u8> {
    let ntt = Ntt::new();
    let records = chain::replay(&ch.net, &ch.blocks[..NB], &ch.state).unwrap();
    let (mut w, pubs) = witness::build(&ntt, &records, inputs);
    if let Some(f) = wt {
        f(&mut w);
    }
    let u: Vec<u8> = inputs.iter().flat_map(|i| i.u.clone()).collect();
    let nu: Vec<u8> = match nut {
        Some(f) => {
            let mut v = w.counts.clone();
            f(&mut v);
            v
        }
        None => w.counts.iter().map(|&c| c.min(cert::NU_MAX)).collect(),
    };
    let man = chain::manifest_v7(&ch.net, NSIG, &ch.anchor, &ch.headers[..NB]);
    let x = chain::instance_v7(&ch.net, &ch.anchor, &ch.headers[..NB], &ch.blocks[..NB], &records, &cert::ubytes_of(&u, NSIG), &nu);
    let (c, rep) = cert::prove_stmt7(&records, &man, &x, fs7::PROFILE_V7, &u, &nu, &w, &pubs, &mut Timer::new(), o);
    if let Some(e) = &rep.transcript_error {
        println!("  (prover transcript error: {e})");
    }
    c.to_bytes().0
}

/// Production chain verifier, default options.
fn verify(ch: &Chain, bytes: &[u8]) -> Result<cert::VerifyReport, Reject> {
    chain::verify_range(&ch.net, &ch.anchor, &ch.headers[..NB], &ch.blocks[..NB], &ch.state, bytes, &mut Timer::new())
}

/// Chain verifier with test options (only the UNSAFE ternarity control uses this).
fn verify_o(ch: &Chain, bytes: &[u8], o: &cert::Opts) -> Result<cert::VerifyReport, Reject> {
    chain::verify_range_inspect(&ch.net, &ch.anchor, &ch.headers[..NB], &ch.blocks[..NB], &ch.state, bytes, &mut Timer::new(), o).0
}

/// The range with record `idx` re-keyed to `pk` and every header accumulator recomputed from the
/// c_tilde of `inputs` (what an adversary must publish for its witness to bind).
fn rekeyed(ch: &Chain, idx: usize, pk: &[u8], inputs: &[SigInput]) -> Chain {
    let mut state = ch.state.clone();
    let enc = ch.blocks[idx / PER].records[idx % PER].clone();
    let rec = chain::AuthRecord::decode(&enc).unwrap();
    state.keys.insert((rec.sender, rec.key_epoch), pk.to_vec());
    let records = chain::replay(&ch.net, &ch.blocks[..NB], &state).unwrap();
    let cts: Vec<[u8; 64]> = (0..NSIG)
        .into_par_iter()
        .map(|i| mlnat::c_tilde_of(&mlnat::mu_of(&mlnat::tr_of(&records[i].pk), &records[i].ctx, &records[i].msg), &mlnat::w1_encode(&inputs[i].u)))
        .collect();
    let mut headers = Vec::with_capacity(NB);
    let mut prev = ch.anchor.clone();
    for b in 0..NB {
        let height = ch.headers[b].height;
        let entries: Vec<(&[u8], &[u8], [u8; 64])> = ch.blocks[b].records.iter().enumerate().map(|(j, e)| (e.as_slice(), records[b * PER + j].pk.as_slice(), cts[b * PER + j])).collect();
        let acc = chain::acc_next(&ch.net, height, &prev.acc, &chain::auth_root(&ch.net, height, &entries));
        let hd = chain::Header { height, parent: prev.id, acc, id: chain::header_id(&prev.id, height, &acc) };
        headers.push(hd.clone());
        prev = hd;
    }
    Chain { net: ch.net, anchor: ch.anchor.clone(), headers, blocks: ch.blocks[..NB].to_vec(), state }
}

/// A relaxed-signer witness for record `idx`: the record keeps its AuthRecord, its key becomes a
/// relaxed key, and the range is rebuilt around it.
fn relaxed_at(ntt: &Ntt, ch: &Chain, honest: &[SigInput], idx: usize, mode: relaxed::Mode) -> (Chain, Vec<SigInput>, relaxed::Signed) {
    let key = relaxed::keygen(ntt, format!("r8-key-{idx}").as_bytes());
    let records = chain::replay(&ch.net, &ch.blocks[..NB], &ch.state).unwrap();
    let s = relaxed::sign(ntt, &key, &records[idx].ctx, &records[idx].msg, mode, format!("r8-{idx}-{mode:?}").as_bytes());
    let mut inputs = honest.to_vec();
    inputs[idx] = s.input.clone();
    let c = rekeyed(ch, idx, &key.pk, &inputs);
    (c, inputs, s)
}

fn chunk_of(i: usize) -> usize {
    i / crate::proj::CHUNK
}

/// The ported r4 S = 1/2 witness, restricted to signatures >= `from`.
fn half_from(w: &mut Witness, from: usize, out: &Mutex<Option<(usize, Vec<usize>)>>) {
    let r = crate::inject_half_from(w, from);
    *out.lock().unwrap() = Some(r);
}

pub fn run() {
    println!("# r3-cert attack8: production profile 0x00070001 at N = {NSIG} (review r8 A.1, A.3)");
    let ntt = Ntt::new();
    let net = chain::network_id(b"attack8");
    let ch = chain::build(net, chain::genesis(&net), 0, NB, PER, 0);
    let honest = honest_inputs(&ntt, &ch);
    let mut t = Tally { pass: 0, total: 0, unexpected: vec![] };
    let def = cert::Opts::default();
    let unsafe_ctl = cert::Opts { drop_ternarity: true, ..Default::default() };

    let hb = prove(&ch, &honest, None, None, &def);
    t.expect("A1.0 honest certificate (control)", &verify(&ch, &hb), true);
    println!("  honest certificate: {} bytes, sha3-256 {}", hb.len(), hex(&sha3_256(&hb)));

    // A1 (i) isolated ternarity in the fourth chunk.
    println!("## A1 (i) S = 1/2 at four interior hint-zero cells, one signature of the fourth 512-signature chunk");
    {
        let shown = Mutex::new(None);
        let tw = |w: &mut Witness| half_from(w, 3 * crate::proj::CHUNK, &shown);
        let b = prove(&ch, &honest, Some(&tw), None, &def);
        let (i, cells) = shown.lock().unwrap().clone().unwrap();
        println!("  signature {i} (chunk {}, block {}), cells {cells:?}: S <- 1/2, Y <- e + 32735, count + 1", chunk_of(i), i / PER);
        t.check(&format!("A1 (i) mutated signature {i} lies in the fourth chunk"), chunk_of(i) == 3);
        t.expect("A1 (i) S = 1/2 witness, full production verifier", &verify(&ch, &b), false);
        let b = prove(&ch, &honest, Some(&tw), None, &unsafe_ctl);
        t.expect("A1 (i) same witness, UNSAFE control without the S^3 = S weight (prover and verifier, same profile)", &verify_o(&ch, &b, &unsafe_ctl), true);
        t.expect("A1 (i) the UNSAFE-control certificate under the full verifier", &verify(&ch, &b), false);
        let b = prove(&ch, &honest, None, None, &unsafe_ctl);
        t.expect("A1 (i) honest witness, UNSAFE control (the control itself is complete)", &verify_o(&ch, &b, &unsafe_ctl), true);
    }

    // A1 (ii) one strict-bound violation in the last signature, modular equation exact.
    println!("## A1 (ii) one strict-bound violation in signature 2047, exact modular equation");
    {
        let last = NSIG - 1;
        let (c, inputs, s) = relaxed_at(&ntt, &ch, &honest, last, relaxed::Mode::Valid);
        println!("  relaxed Valid at {last}: {} attempts, hints {}, max |z| {}", s.attempts, s.hints, s.max_abs_z);
        let b = prove(&c, &inputs, None, None, &def);
        t.expect("A1 (ii) control: re-keyed range, relaxed signature 2047 inside every bound", &verify(&c, &b), true);
        let (c, inputs, s) = relaxed_at(&ntt, &ch, &honest, last, relaxed::Mode::ZEdge(1));
        println!("  relaxed ZEdge(+1) at {last}: {} attempts, hints {}, max |z| {}", s.attempts, s.hints, s.max_abs_z);
        let b = prove(&c, &inputs, None, None, &def);
        t.expect("A1 (ii) signature 2047 has z = +524168 at one coefficient (relation and all other bounds exact)", &verify(&c, &b), false);
        let mut inputs = honest.clone();
        inputs[last].z[L_LAST] += mlnat::QI;
        let b = prove(&ch, &inputs, None, None, &def);
        t.expect("A1 (ii) signature 2047, last z coefficient + q (every mod-q relation unchanged, range only)", &verify(&ch, &b), false);
        let yq = |w: &mut Witness| {
            let b = last * SLOTS + (K - 1) * N + (N - 1);
            w.y[b] += F::from_u64(mlnat::Q as u64);
            w.ei[b] += mlnat::Q as i32;
            w.m = witness::multiplicities(&w.x, &w.y, &w.s, &w.class, w.counts.len());
        };
        let b = prove(&ch, &honest, Some(&yq), None, &def);
        t.expect("A1 (ii) signature 2047, last residual cell Y + q (mod-q relation unchanged, range only)", &verify(&ch, &b), false);
    }

    // A1 (iii) 76 hints in signature 511, published count moved to signature 512.
    println!("## A1 (iii) 76 hints in signature 511 (end of chunk 0), compensating count in signature 512 (chunk 1)");
    {
        let (c, inputs, s) = relaxed_at(&ntt, &ch, &honest, 511, relaxed::Mode::Valid);
        println!("  relaxed Valid at 511: {} attempts, hints {}", s.attempts, s.hints);
        let b = prove(&c, &inputs, None, None, &def);
        t.expect("A1 (iii) control: re-keyed range, relaxed signature 511 inside every bound", &verify(&c, &b), true);
        let (c, inputs, s) = relaxed_at(&ntt, &ch, &honest, 511, relaxed::Mode::Hints(76));
        println!("  relaxed Hints(76) at 511: {} attempts, hints {}", s.attempts, s.hints);
        let seen = Mutex::new((0u8, 0u8));
        let comp = |nu: &mut Vec<u8>| {
            *seen.lock().unwrap() = (nu[511], nu[512]);
            nu[511] -= 1;
            nu[512] += 1;
        };
        let b = prove(&c, &inputs, None, Some(&comp), &def);
        let (c511, c512) = *seen.lock().unwrap();
        println!("  true counts: nu_511 = {c511}, nu_512 = {c512}; published {} and {}", c511 - 1, c512 + 1);
        t.check("A1 (iii) witness: signature 511 has 76 hints and the published counts stay in range", c511 == 76 && c512 < 75);
        t.expect("A1 (iii) published nu_511 = 75 and nu_512 + 1 (total unchanged, across the chunk boundary)", &verify(&c, &b), false);
        let keep = |_: &mut Vec<u8>| {};
        let b = prove(&c, &inputs, None, Some(&keep), &def);
        t.expect("A1 (iii) published nu_511 = 76", &verify(&c, &b), false);
    }

    // A1 (iv) production-layout mutations (positions that differ between N = 128 and 2048).
    println!("## A1 (iv) production-layout mutations, proof regenerated by the dishonest prover");
    {
        let tree = cert::Tree::new(NSIG);
        println!("  N = {NSIG}: GKR tree depth {}, table leaves embedded in the X padding slots: {}", tree.d, tree.embedded);
        t.check("A1 (iv) production layout embeds the multiplicity table (the N = 128 lab layout does not)", tree.embedded && !cert::Tree::new(128).embedded);
        let ms = |w: &mut Witness| {
            let t = (1..w.m.len()).rev().find(|&t| w.m[t] != F::ZERO).unwrap();
            w.m[t] -= F::ONE;
            w.m[t - 1] += F::ONE;
        };
        let b = prove(&ch, &honest, Some(&ms), None, &def);
        t.expect("A1 (iv) embedded table: one count of the highest nonzero entry moved to the entry below", &verify(&ch, &b), false);
        let last = NSIG - 1;
        let sm = |w: &mut Witness| {
            let base = last * SLOTS;
            let a = (0..SLOTS).find(|&t| w.s[base + t] != F::ZERO).unwrap();
            let b = (0..SLOTS).find(|&t| w.s[base + t] == F::ZERO).unwrap();
            w.s.swap(base + a, base + b);
        };
        let b = prove(&ch, &honest, Some(&sm), None, &def);
        t.expect("A1 (iv) selector moved between two cells of signature 2047 (count unchanged)", &verify(&ch, &b), false);
        let xl = |w: &mut Witness| {
            // The final real X coordinate: signature 2047, p = 6 (last z polynomial), k = 255.
            let b = last * SLOTS + 6 * N + (N - 1);
            w.x[b] += F::ONE;
            w.zi[b] += 1;
            w.m = witness::multiplicities(&w.x, &w.y, &w.s, &w.class, w.counts.len());
        };
        let b = prove(&ch, &honest, Some(&xl), None, &def);
        t.expect("A1 (iv) final real X coordinate (signature 2047, z_6[255]) + 1, multiplicities recounted", &verify(&ch, &b), false);
        let yl = |w: &mut Witness| {
            // The final real witness coordinate: Y of signature 2047, p = 7, k = 255.
            let b = last * SLOTS + 7 * N + (N - 1);
            w.y[b] += F::ONE;
            w.m = witness::multiplicities(&w.x, &w.y, &w.s, &w.class, w.counts.len());
        };
        let b = prove(&ch, &honest, Some(&yl), None, &def);
        t.expect("A1 (iv) final real witness coordinate (Y of signature 2047, slot 2047) + 1, multiplicities recounted", &verify(&ch, &b), false);
    }

    // A3 same-pattern substitutions on the prover side.
    println!("## A3 same-pattern configuration substitutions (prover deviates; the verifier builds its configuration from the profile)");
    {
        use cert::LayoutVariant as V;
        for (v, what) in [(V::SwapColumns, "variable order: columns committed as [Y, X, S]"), (V::ClaimOrder, "batching convention: columns opened as [Y, X, S]"), (V::SwapTables, "batching convention: tables committed as [m_even|m_odd, X|Y|S]"), (V::Profile, "another WHIR folding schedule ([6,5,4,5])")] {
            let o = cert::Opts { layout: v, ..Default::default() };
            let r = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| prove(&ch, &honest, None, None, &o)));
            match r {
                Ok(b) => {
                    let res = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| verify(&ch, &b)));
                    match res {
                        Ok(r) => t.expect(&format!("A3 {v:?} ({what})"), &r, false),
                        Err(_) => t.check(&format!("A3 {v:?} ({what}): verifier panicked inside p3 (counted as rejection)"), true),
                    }
                }
                Err(_) => t.check(&format!("A3 {v:?} ({what}): the prover cannot produce a certificate"), true),
            }
        }
        whir_sweep(&mut t);
    }

    println!("ATTACK8 SUMMARY: {}/{} behave as expected; unexpected: {:?}", t.pass, t.total, t.unexpected);
}

/// Last z coefficient index of one signature (L polynomials of N coefficients).
const L_LAST: usize = mlnat::L * N - 1;

/// WHIR configurations near the registered one: which of them induce exactly the registered
/// round table (same transcript pattern), and how they differ from the registered configuration.
fn whir_sweep(t: &mut Tally) {
    let nv = cert::stacked_vars(NSIG);
    let reg = cert::registered_table(fs7::PROFILE_V7, NSIG, false).unwrap();
    let (s0, r0, f0) = crate::pcs::profile(nv);
    let mut cands: Vec<ProtocolParameters> = vec![];
    let mk = |s: usize, r: Vec<usize>, f: Vec<usize>, st: SecurityAssumption, lvl: usize| ProtocolParameters { starting_log_inv_rate: s, round_log_inv_rates: r, folding_factor: FoldingFactor::PerRound(f), soundness_type: st, security_level: lvl, pow_bits: 0 };
    for st in [SecurityAssumption::JohnsonBound, SecurityAssumption::UniqueDecoding, SecurityAssumption::CapacityBound] {
        for lvl in (240..=300).filter(|&l| !(st == SecurityAssumption::JohnsonBound && l == 272)) {
            cands.push(mk(s0, r0.clone(), f0.clone(), st, lvl));
        }
    }
    for a in 3..=8 {
        for b in 3..=8 {
            for c in 3..=8 {
                let d = 20i64 - (a + b + c) as i64;
                if (3..=8).contains(&d) && vec![a, b, c, d as usize] != f0 {
                    cands.push(mk(s0, r0.clone(), vec![a, b, c, d as usize], SecurityAssumption::JohnsonBound, 272));
                }
            }
        }
    }
    for s in 2..=6 {
        for d1 in -1i64..=1 {
            for d2 in -1i64..=1 {
                for d3 in -1i64..=1 {
                    let r = vec![(r0[0] as i64 + d1) as usize, (r0[1] as i64 + d2) as usize, (r0[2] as i64 + d3) as usize];
                    if s != s0 || r != r0 {
                        cands.push(mk(s, r, f0.clone(), SecurityAssumption::JohnsonBound, 272));
                    }
                }
            }
        }
    }
    let base_cfg = WhirConfig::<EF, F, reg7::Reg>::new_with_initial_claims(nv, mk(s0, r0.clone(), f0.clone(), SecurityAssumption::JohnsonBound, 272), 5).unwrap();
    let base_dbg = strip_params(&format!("{base_cfg:?}"));
    let (mut infeasible, mut other, mut same) = (0, 0, vec![]);
    // build_table asserts on shapes outside the registered family; those panics are expected.
    let hook = std::panic::take_hook();
    std::panic::set_hook(Box::new(|_| {}));
    for p in &cands {
        let Ok(cfg) = WhirConfig::<EF, F, reg7::Reg>::new_with_initial_claims(nv, p.clone(), 5) else {
            infeasible += 1;
            continue;
        };
        let ws = p3_whir::WhirShape::new(&cfg, 2);
        let tb = std::panic::catch_unwind(|| reg7::build_table(fs7::PROFILE_V7, NSIG, &reg7::front(NSIG), &ws));
        match tb {
            Ok(tb) if tb.rounds == reg.rounds && tb.formal_len == reg.formal_len => {
                let derived_equal = strip_params(&format!("{cfg:?}")) == base_dbg;
                same.push((p.clone(), derived_equal));
            }
            _ => other += 1,
        }
    }
    std::panic::set_hook(hook);
    println!("  WHIR sweep: {} parameter sets other than the registered (4, [7, 9, 11], [6, 5, 5, 4], JohnsonBound, 272): {infeasible} rejected by p3, {other} induce another round table (the adapter poisons on them), {} induce the registered table", cands.len(), same.len());
    let mut by: std::collections::BTreeMap<String, Vec<usize>> = Default::default();
    for (p, _) in &same {
        by.entry(format!("{:?}", p.soundness_type)).or_default().push(p.security_level);
    }
    for (k, v) in &by {
        println!("    registered table also induced by {k}, security_level {}..={} ({} values), same rates and folds", v.first().unwrap(), v.last().unwrap(), v.len());
    }
    let all_derived = same.iter().all(|(_, d)| *d);
    let only_labels = same.iter().all(|(p, _)| p.starting_log_inv_rate == s0 && p.round_log_inv_rates == r0 && format!("{:?}", p.folding_factor) == format!("{:?}", FoldingFactor::PerRound(f0.clone())));
    t.check(&format!("A3 WHIR sweep: {} other configurations induce the registered table; any that did would have the registered rates and folds and the same derived WhirConfig (labels aside)", same.len()), same.is_empty() || (all_derived && only_labels));
}

/// Only so that a WhirConfig over the adapter can be printed (the challenger is a phantom type there).
impl std::fmt::Debug for reg7::Reg {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("Reg")
    }
}

/// WhirConfig's Debug without its `params: ProtocolParameters { .. }` field.
fn strip_params(s: &str) -> String {
    match s.find("params: ProtocolParameters {") {
        Some(a) => {
            let z = a + s[a..].find('}').unwrap() + 1;
            format!("{}{}", &s[..a], &s[z..])
        }
        None => s.to_string(),
    }
}

fn sha3_256(b: &[u8]) -> [u8; 32] {
    use sha3::Digest;
    sha3::Sha3_256::digest(b).into()
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}
