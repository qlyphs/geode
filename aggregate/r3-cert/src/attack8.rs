//! Round 8, review A.1 and A.3: dishonest witnesses and same-pattern configuration substitutions
//! under the production profile 0x00070001 at N = 2048 (not the lab ids), each checked by the
//! chain verifier `chain::verify_range` with the default options.
//!
//! A.1 ports the targeted negative tests of the N = 128 lab suites to the production indexing,
//! chunking and embedded-table paths: the isolated S = 1/2 ternarity witness in the fourth
//! 512-signature chunk (with its UNSAFE control), a strict-bound violation in signature 2047 that
//! keeps the exact modular equation, the 76-hint / compensating-count attack across signatures
//! 511 and 512 (the first chunk boundary), and production-layout mutations. Every certificate is
//! regenerated by the dishonest prover over the full QLYAUTH7 transcript.
//!
//! The relaxed-signer witnesses need a key the relaxed signer controls. The harness builds that
//! range as an adversary would have to: the state registers the relaxed key for the sender and
//! the headers carry accumulators recomputed from the relaxed c_tilde. A node would have refused
//! such a block (native verification fails); the archive certificate must refuse it on its own.
//! The same construction with a relaxed signature inside every bound is the control (ACCEPT).
//!
//! A.3 substitutes same-pattern conventions (column order, claim order, table order) and other
//! WHIR configurations on the prover side, and sweeps the WHIR parameter space for any
//! configuration that induces the registered round table. Command: `r3-cert attack8`.

